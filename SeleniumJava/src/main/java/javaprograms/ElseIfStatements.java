package javaprograms;

public class ElseIfStatements {
	
	public static void main(String[] args) {
		
		
		int i=0;
		
		
		if (i==1) {
			System.out.println(i);
			
		}
		else if (i==0) {
			System.out.println("else if 1");
		}
		else if(i==2) {
			System.out.println("else if 2");
		}
		else {
			System.out.println("else");
		}
	}

}
